#!/usr/bin/env python3
"""
check_header.py — Generates the TEST VECTORS of the protocol v3 header and
checks their symmetry (packing and decoding).

The header is a uint32 word sent BIG-ENDIAN:

    header = (pktId << 24) | (flags << 22) | (idx << 17) | (cnt << 12) | bitmask

Each vector maps (pktId, flags, idx, cnt, bitmask) to the 4 expected on-air
bytes. The vectors feed the C test (esp32/main/test/test_header.c -> includes
header_vectors.h): if the ESP32 packs differently, its 4 bytes do not match
the vectors and the test fails. The watch side is verified on the device.

Usage:
    python tools/check_header.py            # self-check and write header_vectors.h
    python tools/check_header.py --check     # self-check only (writes nothing)
"""

import os
import sys

PKTID_SHIFT, FLAGS_SHIFT, IDX_SHIFT, CNT_SHIFT = 24, 22, 17, 12
PKTID_MASK, FLAGS_MASK, IDX_MASK, CNT_MASK, BITMASK_MASK = 0xFF, 0x03, 0x1F, 0x1F, 0xFFF

# Timestamp bits always set in DELTA packets (8, 10, 11).
DELTA_FORCED = (1 << 8) | (1 << 10) | (1 << 11)   # 0xD00


def pack_header(pkt_id, flags, idx, cnt, bitmask):
    """Packs the fields into the header word (32 bits)."""
    return (((pkt_id & PKTID_MASK) << PKTID_SHIFT)
            | ((flags & FLAGS_MASK) << FLAGS_SHIFT)
            | ((idx & IDX_MASK) << IDX_SHIFT)
            | ((cnt & CNT_MASK) << CNT_SHIFT)
            | (bitmask & BITMASK_MASK)) & 0xFFFFFFFF


def to_be_bytes(h):
    return [(h >> 24) & 0xFF, (h >> 16) & 0xFF, (h >> 8) & 0xFF, h & 0xFF]


def unpack_bytes(b):
    """Inverse decoding (as the ESP32 does it), for the self-check."""
    h = (b[0] << 24) | (b[1] << 16) | (b[2] << 8) | b[3]
    return {
        "pktId": (h >> PKTID_SHIFT) & PKTID_MASK,
        "flags": (h >> FLAGS_SHIFT) & FLAGS_MASK,
        "idx": (h >> IDX_SHIFT) & IDX_MASK,
        "cnt": (h >> CNT_SHIFT) & CNT_MASK,
        "bitmask": h & BITMASK_MASK,
    }


# (pktId, flags, idx, cnt, bitmask) — representative and edge cases.
VECTORS = [
    (0,   0, 0,  1,  0),            # minimum
    (1,   0, 0,  3,  0),            # FULL chunk 0/3
    (1,   0, 1,  3,  0),            # FULL chunk 1/3
    (1,   0, 2,  3,  0),            # FULL chunk 2/3
    (255, 2, 30, 31, 0),           # every field at its maximum
    (7,   1, 0,  1,  DELTA_FORCED), # DELTA keep-alive (timestamps only)
    (42,  1, 0,  1,  DELTA_FORCED | (1 << 0)),  # DELTA with 1 changed field (HR)
    (170, 1, 1,  2,  0xFFF),        # DELTA with every bit set (== FULL byte for byte)
    (128, 2, 17, 18, 0),           # BATCH of 6 samples, chunk 17/18
    (85,  2, 0,  18, 0),           # BATCH chunk 0/18
    (200, 3, 5,  6,  0),           # reserved flags (11): the decoder must drop it
]


def build_records():
    recs = []
    for (pkt_id, flags, idx, cnt, bitmask) in VECTORS:
        h = pack_header(pkt_id, flags, idx, cnt, bitmask)
        b = to_be_bytes(h)
        recs.append({
            "pktId": pkt_id, "flags": flags, "idx": idx,
            "cnt": cnt, "bitmask": bitmask,
            "header": h, "bytes": b,
        })
    return recs


def self_verify(recs):
    ok = True
    for r in recs:
        dec = unpack_bytes(r["bytes"])
        for k in ("pktId", "flags", "idx", "cnt", "bitmask"):
            if dec[k] != r[k]:
                print("MISMATCH on %s: expected %d, decoded %d (bytes=%s)"
                      % (k, r[k], dec[k], r["bytes"]))
                ok = False
    return ok


def write_c_header(recs, path):
    lines = []
    lines.append("// header_vectors.h — GENERATED by tools/check_header.py. DO NOT edit by hand.")
    lines.append("// Test vectors of the protocol v3 header (used by test_header.c).")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint8_t  pktId, flags, idx, cnt;")
    lines.append("    uint16_t bitmask;")
    lines.append("    uint8_t  bytes[4];   // expected header, BIG-ENDIAN")
    lines.append("} header_vec_t;")
    lines.append("")
    lines.append("static const header_vec_t HEADER_VECTORS[] = {")
    for r in recs:
        lines.append("    { %d, %d, %d, %d, 0x%03X, { %d, %d, %d, %d } },"
                     % (r["pktId"], r["flags"], r["idx"], r["cnt"], r["bitmask"],
                        r["bytes"][0], r["bytes"][1], r["bytes"][2], r["bytes"][3]))
    lines.append("};")
    lines.append("static const int HEADER_VECTORS_N = %d;" % len(recs))
    lines.append("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("written", path)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    recs = build_records()

    if not self_verify(recs):
        print("SELF-CHECK FAILED: encoding/decoding of the vectors is not symmetric.")
        return 1
    print("self-check OK (%d vectors, symmetric packing)" % len(recs))

    if "--check" in sys.argv:
        return 0

    test_dir = os.path.join(root, "esp32", "main", "test")
    os.makedirs(test_dir, exist_ok=True)
    write_c_header(recs, os.path.join(test_dir, "header_vectors.h"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
